"""Live proof page, served BY the mainframe: every value is read from this machine at request time.
Run on the VM:  cd ~/eeg-review-queue && nohup .venv/bin/python scripts/proof_page.py > runs/proof_page.log 2>&1 &
View:           ssh -i ~/.ssh/linuxone_ibmz -N -L 8070:localhost:8070 linux1@YOUR_LINUXONE_IP  ->  http://localhost:8070
"""
import html, json, subprocess, urllib.request
from flask import Flask

app = Flask(__name__)


def sh(cmd):
    try:
        return subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=15).stdout.strip()
    except Exception as e:
        return f"({e.__class__.__name__})"


def get(url):
    try:
        return json.dumps(json.load(urllib.request.urlopen(url, timeout=3)), indent=1)
    except Exception as e:
        return f"(not reachable: {e.__class__.__name__})"


def snapml_version():
    from importlib.metadata import PackageNotFoundError, version
    try:
        return "snapml " + version("snapml")
    except PackageNotFoundError:
        return "(not installed)"


@app.get("/")
def proof():
    rows = [
        ("Chip architecture (uname -m)", sh("uname -m")),
        ("Manufacturer and machine type (/proc/sysinfo)", sh("grep -E '^(Manufacturer|Type|Model Capacity)' /proc/sysinfo")),
        ("IBM on-chip AI accelerator (nnpa flag in /proc/cpuinfo)",
         "present" if " nnpa" in sh("grep -m1 '^features' /proc/cpuinfo") else "absent"),
        ("IBM zDNN accelerator library", sh("dpkg -l libzdnn0 | tail -1 | tr -s ' ' | cut -d' ' -f2,3")),
        ("IBM Snap ML", snapml_version()),
        ("CPUs and memory", sh("nproc") + " CPUs | " + sh("free -h | sed -n 2p | tr -s ' '")),
        ("Operating system", sh("grep PRETTY_NAME /etc/os-release | cut -d= -f2")),
        ("Kernel (uname -a)", sh("uname -a")),
        ("Our programs running on this machine right now",
         sh("ps -o pid,etime,pcpu,args -u $(whoami) | grep -E '[s]erver.py|[l]lama-server|[s]rc.experiments|[e]val_|[s]cale_test' | cut -c1-170")),
        ("Live seizure app on this machine (port 8050, /api/metrics)", get("http://127.0.0.1:8050/api/metrics")),
        ("IBM Granite LLM loaded on this machine (port 8081, /v1/models)", get("http://127.0.0.1:8081/v1/models")[:700]),
        ("Clock on this machine", sh("date")),
    ]
    body = "".join(f"<tr><th>{html.escape(k)}</th><td><pre>{html.escape(v)}</pre></td></tr>" for k, v in rows)
    return f"""<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="refresh" content="5">
<title>Proof: running on IBM LinuxONE</title>
<style>body{{font-family:Inter,system-ui,sans-serif;background:#fafafa;color:#1a1a1a;margin:32px}}
h1{{font-size:22px;margin:0 0 4px}} p{{color:#555;margin:0 0 20px}}
table{{border-collapse:collapse;width:100%;background:#fff}} th,td{{border-bottom:1px solid #e5e5e5;padding:10px;vertical-align:top;text-align:left}}
th{{width:30%;font-weight:600;font-size:14px}} pre{{margin:0;white-space:pre-wrap;font-size:13px}}</style></head>
<body><h1>Live proof: this page is generated by the IBM LinuxONE mainframe</h1>
<p>Every value below is read from the machine itself when the page loads. It refreshes every 5 seconds.</p>
<table>{body}</table></body></html>"""


if __name__ == "__main__":
    app.run(host="127.0.0.1", port=8070)
